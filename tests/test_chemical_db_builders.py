import csv
import gzip
from pathlib import Path

from massflow.agent_tools.chemical_db_builders import build_chebi_annotation_table


def test_build_chebi_annotation_table(tmp_path: Path) -> None:
    chebi_dir = tmp_path / "chebi"
    chebi_dir.mkdir()

    _write_gz(
        chebi_dir / "compounds.tsv.gz",
        [
            ["id", "name", "status_id", "source", "parent_id", "merge_type", "chebi_accession", "definition", "ascii_name", "stars", "modified_on", "release_date"],
            ["1", "water", "1", "manual", "", "", "CHEBI:15377", "", "water", "3", "", ""],
        ],
    )
    _write_gz(
        chebi_dir / "chemical_data.tsv.gz",
        [
            ["id", "compound_id", "formula", "charge", "mass", "monoisotopic_mass", "status_id", "structure_id", "is_autogenerated"],
            ["10", "1", "H2O", "0", "18.015", "18.01056", "1", "100", "false"],
        ],
    )
    _write_gz(
        chebi_dir / "structures.tsv.gz",
        [
            ["id", "compound_id", "status_id", "molfile", "smiles", "standard_inchi", "standard_inchi_key", "dimension", "default_structure"],
            ["100", "1", "1", "", "O", "InChI=1S/H2O/h1H2", "XLYOFNOQVPJJNP-UHFFFAOYSA-N", "2", "true"],
        ],
    )

    output_path = build_chebi_annotation_table(str(chebi_dir))
    with Path(output_path).open("r", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle, delimiter="\t"))

    assert len(rows) == 1
    assert rows[0]["source_record_id"] == "CHEBI:15377"
    assert rows[0]["formula"] == "H2O"
    assert rows[0]["smiles"] == "O"


def _write_gz(file_path: Path, rows: list[list[str]]) -> None:
    with gzip.open(file_path, "wt", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, delimiter="\t")
        writer.writerows(rows)
